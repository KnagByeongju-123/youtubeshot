DIALOGUE = []
_TAG = re.compile(r'@(\S+) "([^"]+)"')


def _build():
    story = []
    for line in STORY_SRC.split("\n"):
        for who, text in _TAG.findall(line):
            DIALOGUE.append((text, who))
        story.append(_TAG.sub(lambda m: '"' + m.group(2) + '"', line))
    return "\n".join(story)


