# -*- coding: utf-8 -*-
"""벌 공격을 화살로 막는 장면 — 단계마다 어려워짐(1단계 1마리 → 2단계 2마리 → 3단계 3마리 → 여왕벌).
벌이 날아갈 길과 맞을 시각만 적으면, 화살 쏘는 시각(거리로 계산)·전사 자세·점수판·점수 글자·떨어지는 길을
자동으로 계산해 장면 파일(JSON)을 만듦.

  python 블록애니/벌_단계_만들기.py 블록애니/장면_벌단계.json
  xvfb-run -a .blender_venv/bin/python 블록애니.py 장면 블록애니/장면_벌단계.json 결과.mp4
"""
import json
import math
import sys

ARCHER_X = -4.5
BOW = {"활쏘기": (-3.6, 1.45), "위로쏘기": (-3.8, 2.2)}  # 화살이 나가는 곳(x, 높이)
ARROW_SPEED = 15.0  # m/초

# 단계: (제목, 제목 시각, [벌...])  벌 = {"길": [(초, x, 높이), ...마지막 = 맞는 곳], "점수", "크기", "색"}
WAVES = [
    ("1단계", 0.3, [
        {"길": [(1.6, 9.5, 1.8), (4.0, 0.5, 1.7)], "점수": 100},
    ]),
    ("2단계", 5.0, [
        {"길": [(5.8, 9.5, 5.0), (7.2, 3.5, 4.3), (8.0, 0.5, 3.4)], "점수": 200},
        {"길": [(6.6, 9.5, 1.2), (8.4, 3.5, 2.0), (9.5, -0.5, 1.5)], "점수": 200},
    ]),
    ("3단계", 10.8, [
        {"길": [(11.6, 9.5, 2.0), (12.4, 6.0, 3.6), (13.2, 3.0, 1.4), (13.8, 1.0, 2.6)], "점수": 300},
        {"길": [(12.2, 9.5, 5.4), (13.4, 5.0, 4.6), (14.4, 1.5, 3.8), (15.0, -0.5, 3.2)], "점수": 300},
        {"길": [(12.8, 9.5, 0.9), (13.6, 6.5, 2.4), (14.4, 4.0, 0.8), (15.3, 1.5, 2.3), (16.4, -2.4, 1.45)],
         "점수": 300, "놀람": 15.7},
    ]),
]
# 여왕벌: 화살 3발을 맞아야 쓰러짐, 중간에 침을 쏨(전사는 점프로 피함)
QUEEN = {"제목": ("여왕벌 등장!", 17.6),
         "길": [(18.6, 10.5, 4.5), (19.6, 5.0, 3.2), (20.4, 3.0, 4.6), (21.4, 2.0, 3.0), (22.4, 3.2, 4.4),
               (23.2, 1.8, 2.6), (24.2, 0.6, 3.6)],
         "맞음": [20.4, 22.4, 24.2], "침": 21.4, "점수": 1000, "크기": 3.2, "색": "#ffa41f"}
CLEAR = 25.6
TOTAL = 28.5


def pos_at(path, t):
    """길 위의 t 초 위치(블록애니.py 와 같은 부드러운 이음)."""
    if t <= path[0][0]:
        return path[0][1:]
    for (t0, *a), (t1, *b) in zip(path, path[1:]):
        if t0 <= t <= t1:
            u = (t - t0) / (t1 - t0)
            u = u * u * (3 - 2 * u)
            return [x + (y - x) * u for x, y in zip(a, b)]
    return path[-1][1:]


def main(out):
    objs, shots, surprises, score_changes = [], [], [], [[0, "점수 0"]]
    score = 0

    def title(txt, t0, dur=1.6, color="#ffffff", size=1.0):
        objs.append({"모양": "글자", "내용": txt, "글자크기": size, "색": color,
                     "동작": [{"초": t0, "위치": [0, -1, 5.4]}, {"초": t0 + dur, "위치": [0, -1, 5.6]}]})

    def hit(x, z, t, pts):
        nonlocal score
        objs.append({"모양": "글자", "내용": f"+{pts}", "동작": [
            {"초": t, "위치": [x, -0.6, z + 0.8]}, {"초": t + 0.9, "위치": [x, -0.6, z + 1.8]}]})
        score += pts
        score_changes.append([t, f"점수 {score}"])

    def arrow_to(x, z, t_hit):
        pose = "위로쏘기" if z > 2.8 else "활쏘기"
        bx, bz = BOW[pose]
        d = math.hypot(x - bx, z - bz)
        t_fire = t_hit - d / ARROW_SPEED * 1.4  # 부드러운 이음은 끝에서 느려지므로 조금 일찍 쏨
        objs.append({"모양": "화살", "동작": [{"초": round(t_fire, 2), "위치": [bx, 0, bz]},
                                             {"초": t_hit, "위치": [x - 0.4, 0, z]}]})
        shots.append((t_fire, pose))

    for name, t0, bees in WAVES:
        title(name, t0)
        for b in bees:
            th, x, z = b["길"][-1]
            path = [{"초": t, "위치": [px, 0, pz]} for t, px, pz in b["길"]]
            path.append({"초": th + 0.7, "위치": [x + 0.4, 0, 0.15]})  # 빙글 돌며 바닥으로
            objs.append({"모양": "벌", "크기": b.get("크기", 1.6), "맞은초": th, "동작": path})
            arrow_to(x, z, th)
            hit(x, z, th, b["점수"])
            if "놀람" in b:
                surprises.append(b["놀람"])

    # 여왕벌
    q = QUEEN
    title(q["제목"][0], q["제목"][1], 1.8, "#ff5a5a", 1.1)
    qpath = [{"초": t, "위치": [x, 0, z]} for t, x, z in q["길"]]
    tq, xq, zq = q["길"][-1]
    qpath.append({"초": tq + 0.9, "위치": [xq + 0.6, 0, 0.3]})
    objs.append({"모양": "벌", "크기": q["크기"], "색": q["색"], "맞은초": q["맞음"][-1], "동작": qpath})
    for th in q["맞음"]:
        x, z = pos_at(q["길"], th)
        arrow_to(x - 0.5, z, th)  # 큰 몸이라 앞쪽에 맞음
    x, z = pos_at(q["길"], q["맞음"][-1])
    hit(x, z, q["맞음"][-1], q["점수"])
    # 침 발사 → 전사 점프
    sx, sz = pos_at(q["길"], q["침"])
    objs.append({"모양": "광선", "색": "#ffd21f", "동작": [{"초": q["침"], "위치": [sx - 0.8, 0, sz]},
                                                         {"초": q["침"] + 0.9, "위치": [-9.5, 0, 0.6]}]})
    jump_t = q["침"] + 0.15

    title("클리어!", CLEAR, TOTAL - CLEAR, "#ffe14d", 1.3)
    objs.append({"모양": "글자", "내용": "점수 0", "글자크기": 0.55, "색": "#ffffff", "바뀜": score_changes,
                 "동작": [{"초": 0, "위치": [5.6, -1, 7.3]}, {"초": TOTAL, "위치": [5.6, -1, 7.3]}]})

    # 전사 동작: 쏘기 0.35초 전에 겨눔, 놀람, 점프, 만세
    acts = [{"초": 0, "자세": "서기", "위치": [ARCHER_X, 0, 0]}, {"초": 1.0, "자세": "놀람"}]
    ev = [(t - 0.35, p) for t, p in shots] + [(t, "놀람") for t in surprises]
    ev += [(jump_t, "점프"), (CLEAR, "만세")]
    for t, p in sorted(ev):
        acts.append({"초": round(t, 2), "자세": p})
    acts += [{"초": jump_t, "위치": [ARCHER_X, 0, 0]}, {"초": jump_t + 0.35, "위치": [ARCHER_X, 0, 2.4]},
             {"초": jump_t + 0.75, "위치": [ARCHER_X, 0, 0]}]
    acts.append({"초": round(jump_t + 0.8, 2), "자세": "활쏘기"})
    acts.sort(key=lambda k: k["초"])

    scene = {
        "캐릭터": "캐릭터.json", "초": TOTAL, "fps": 24, "크기": [1920, 1080], "픽셀": 6, "꼬마": 1.5,
        "배경": "레트로",
        "무대": {"바닥": [-9, 9], "발판": [[-9, -5, 4.8], [5.5, 9, 6.0]], "사다리": [[-5.6, 0, 4.8]]},
        "인물": [{"이름": "전사", "위치": [ARCHER_X, 0, 0], "방향": 60, "동작": acts}],
        "물체": objs,
        "효과음": [{"초": CLEAR, "소리": "승리"}],
        "배경음": {"곡": "레트로전투", "크기": 0.35, "끝": CLEAR - 0.1},
        "카메라": [{"초": 0, "위치": [0, -30, 3.6], "보는곳": [0, 0, 3.6], "직교": 16}],
    }
    json.dump(scene, open(out, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print("저장:", out, "| 최종 점수", score, "| 화살", len(shots), "발")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "블록애니/장면_벌단계.json")
