def swing(p, t0, t1, amp, period, arms=True):
    legL,legR,armL,armR=[part(p,n) for n in ('leg_left','leg_right','arm_left','arm_right')]
    t=t0; s=1; pts=[]
    while t<t1-1e-6: pts.append((t+period/4,s)); t+=period/2; s=-s
    pts=[q for q in pts if q[0]<t1]
    for g,sg in [(legL,1),(legR,-1)]+([(armL,-1),(armR,1)] if arms else []):
        R(g,[(t0,(0,0,0))]+[(tt,(sg*ss*amp,0,0)) for tt,ss in pts]+[(t1,(0,0,0))],'catmullrom')
def walk(p,t0,t1,amp=24,period=0.7,arms=True): swing(p,t0,t1,amp,period,arms)
def run(p,t0,t1,amp=45,period=0.4): swing(p,t0,t1,amp,period)
def wave(arm, t0, t1, side=1):
    """손 흔들기: side=1 왼팔(+z 회전), -1 오른팔"""
    pts=[(t0,(0,0,0)),(t0+0.3,(0,0,150*side))]; t=t0+0.3; s=1
    while t<t1-0.35: t+=0.25; pts.append((t,(0,0,(150-25*(s>0))*side))); s=-s
    R(arm,pts+[(t1,(0,0,0))])
def yaw_to(dx,dz): return math.degrees(math.atan2(dx,-dz))
def fly(pl, pts, hold=None):
    """비행기 날기: pts=[(t,(x,y,z)),...] 지나는 점.  방향은 다음 점 쪽"""
    P(pl,pts,'catmullrom')
    ys=[]
    for i,(t,p) in enumerate(pts):
        q=pts[min(i+1,len(pts)-1)][1] if i<len(pts)-1 else p; o=pts[i-1][1] if i>0 else p
        d=(q[0]-o[0],q[2]-o[2]); ys.append((t,(-8,yaw_to(*d) if any(d) else 0,0)))
    R(pl,ys)

