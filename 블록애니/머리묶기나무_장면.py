def yaw(g, pts, interp='linear'): R(g,[(t,(0,y,0)) for t,y in pts],interp)
def part(g, name): return find(g, g['name'].replace('root',name))
def keys(g, pts):
    P(g,[(t,(x,(r[0] if r else 0),z)) for t,x,z,y,*r in pts]); yaw(g,[(t,y) for t,x,z,y,*r in pts])
def swing(p, t0, t1, amp, period, arms=True):
    legL,legR,armL,armR=[part(p,n) for n in ('leg_left','leg_right','arm_left','arm_right')]
    t=t0; s=1; pts=[]
    while t<t1-1e-6: pts.append((t+period/4,s)); t+=period/2; s=-s
    pts=[q for q in pts if q[0]<t1]
    for g,sg in [(legL,1),(legR,-1)]+([(armL,-1),(armR,1)] if arms else []):
        R(g,[(t0,(0,0,0))]+[(tt,(sg*ss*amp,0,0)) for tt,ss in pts]+[(t1,(0,0,0))],'catmullrom')
def walk(p,t0,t1,amp=24,period=0.7,arms=True): swing(p,t0,t1,amp,period,arms)
def jitter(g, t0, t1, base, d, period):
    """손 바쁘게(허둥지둥 = 짧은 주기, 차분 = 긴 주기): base 각도 주변으로 흔듦"""
    pts=[(t0,base)]; t=t0+period; s=1
    while t<t1-period/2: pts.append((t,tuple(b+s*e for b,e in zip(base,d)))); t+=period; s=-s
    R(g,pts+[(t1,base)],'catmullrom')

