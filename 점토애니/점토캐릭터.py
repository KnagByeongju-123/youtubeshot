def 저승사자():
    """검은 갓 + 검은 도포, 하얀 얼굴. 무섭기보다 살짝 시무룩한 귀여운 점토."""
    얼굴 = clay_mat("하얀얼굴", (0.72, 0.72, 0.70), sss=0.06)
    도포 = clay_mat("검은도포", (0.018, 0.018, 0.022), rough=0.7)
    갓 = clay_mat("검은갓", (0.012, 0.012, 0.014), rough=0.45)
    동정 = clay_mat("흰동정", (0.93, 0.92, 0.88))
    신 = clay_mat("검은신", (0.03, 0.03, 0.03))
    눈그늘 = clay_mat("눈그늘", (0.55, 0.55, 0.60))

    # 도포: 아래가 넓은 긴 옷 (발끝까지)
    part("cone", "도포", (0, 0, 0.78), (1, 0.8, 1), 도포, lump=0.03, radius1=0.50, radius2=0.24, depth=1.42)
    for sx in (-1, 1):
        part("sphere", f"신{sx}", (0.15 * sx, -0.27, 0.06), (0.11, 0.16, 0.07), 신, lump=0.0)
        # 넓은 소매 (아래로 넓게 퍼짐)
        part("cone", f"소매{sx}", (0.36 * sx, 0, 1.08), (1, 0.85, 1), 도포, rot=(0, 15 * sx, 0), lump=0.02,
             radius1=0.20, radius2=0.11, depth=0.62)
        part("sphere", f"손{sx}", (0.44 * sx, -0.02, 0.73), (0.08, 0.075, 0.09), 얼굴, lump=0.0)
        # 흰 동정(목깃): V 자
        part("cyl", f"동정{sx}", (0.075 * sx, -0.205, 1.31), (0.03, 0.03, 0.16), 동정,
             rot=(10, 28 * sx, 0), lump=0.0, bevel=0.3)
    part("cyl", "목", (0, 0, 1.48), (0.11, 0.11, 0.06), 얼굴, lump=0.0)
    # 머리
    HZ = 1.78
    part("sphere", "머리", (0, 0, HZ), (0.38, 0.35, 0.36), 얼굴, lump=0.025)
    # 검은 머리카락 (갓 아래, 뒤로 목덜미까지)
    part("sphere", "머리카락", (0, 0.06, HZ + 0.03), (0.395, 0.37, 0.37), 갓, rot=(-28, 0, 0), lump=0.02)
    # 얼굴: 졸린 듯 처진 눈 + 눈 밑 그늘 + 일자 입
    FY = -0.335
    for sx in (-1, 1):
        part("sphere", f"눈그늘{sx}", (0.13 * sx, FY + 0.025, HZ - 0.03), (0.075, 0.02, 0.05), 눈그늘, lump=0.0)
        눈(0.13 * sx, FY + 0.0, HZ + 0.0, sx=0.05, sz=0.055)
        # 처진 눈썹 (바깥쪽이 아래로)
        part("cyl", f"눈썹{sx}", (0.13 * sx, FY + 0.0, HZ + 0.10), (0.012, 0.012, 0.06),
             M["검은눈"], rot=(0, 90 + 15 * sx, 0), lump=0.0, bevel=0.5)
    part("cyl", "입", (0, FY + 0.01, HZ - 0.15), (0.01, 0.01, 0.05), M["입"], rot=(0, 90, 0), lump=0.0, bevel=0.5)
    # 갓: 넓은 챙 + 높은 모자 통
    part("cyl", "갓챙", (0, 0, HZ + 0.25), (0.66, 0.66, 0.018), 갓, lump=0.0, bevel=0.5)
    part("cone", "갓통", (0, 0, HZ + 0.43), (1, 1, 1), 갓, lump=0.0, radius1=0.20, radius2=0.18, depth=0.36)
    # 갓끈: 턱 밑에서 가슴으로 늘어진 구슬 끈 (얼굴 옆을 지나면 떠 보여서 앞가슴에만)
