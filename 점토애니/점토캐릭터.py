def 민화호랑이():
    """까치호랑이 민화처럼: 동그랗게 부릅뜬 큰 눈, 넓적한 얼굴, 익살스러운 웃음, 네 발로 섬."""
    주황 = (0.93, 0.55, 0.13)
    검정 = (0.06, 0.05, 0.05)
    몸 = clay_mat("호랑이몸", 주황, stripe=("Y", 1.5, 검정, 0.3))
    다리 = clay_mat("호랑이다리", 주황, stripe=("Z", 1.1, 검정, 0.28))
    머리 = clay_mat("호랑이머리", 주황)
    흰 = clay_mat("흰털", (0.96, 0.94, 0.88))
    줄 = clay_mat("검은줄", 검정)
    노랑 = clay_mat("노란눈", (0.98, 0.80, 0.10), rough=0.3)
    코 = clay_mat("코", (0.35, 0.15, 0.12))

    # 몸통 + 흰 배
    part("sphere", "몸통", (0, 0.35, 0.78), (0.42, 0.78, 0.40), 몸, lump=0.035)
    part("sphere", "배", (0, 0.30, 0.58), (0.33, 0.62, 0.24), 흰, lump=0.02)
    # 다리 4개 + 흰 발
    for sy in (-0.18, 0.88):
        for sx in (-1, 1):
            part("cyl", f"다리{sx}{sy}", (0.24 * sx, sy, 0.33), (0.13, 0.13, 0.28), 다리, lump=0.02)
            part("sphere", f"발{sx}{sy}", (0.24 * sx, sy - 0.06, 0.08), (0.16, 0.19, 0.09), 흰, lump=0.0)
    # 꼬리: 위로 휘어 올라감, 주황·검정 번갈아 (줄무늬)
    import math
    for k in range(12):
        t = k / 11
        y = 1.08 + 0.38 * math.sin(t * 1.9)
        z = 0.85 + 0.85 * t + 0.10 * math.sin(t * 6)
        part("sphere", f"꼬리{k}", (0, y, z), (0.075,) * 3, 줄 if k % 3 == 2 else 머리, lump=0.0)
    # 머리: 크고 넓적하게
    HY, HZ = -0.52, 1.18
    part("sphere", "머리", (0, HY, HZ), (0.58, 0.47, 0.48), 머리, lump=0.03)
    # 볼 흰 털 + 주둥이
    for sx in (-1, 1):
        part("sphere", f"볼털{sx}", (0.36 * sx, HY - 0.28, HZ - 0.17), (0.22, 0.14, 0.17), 흰, lump=0.015)
    part("sphere", "주둥이", (0, HY - 0.43, HZ - 0.16), (0.27, 0.16, 0.19), 흰, lump=0.01)
    part("sphere", "코", (0, HY - 0.585, HZ - 0.06), (0.085, 0.045, 0.06), 코, lump=0.0)
    half_torus("입", (0, HY - 0.57, HZ - 0.20), M["입"], major=0.10, minor=0.02)
    # 민화 눈: 흰자 + 노란 동그라미 + 검은 눈동자 (부릅뜬 느낌)
    for sx in (-1, 1):
        ex, ez = 0.21 * sx, HZ + 0.14
        part("sphere", f"흰자{sx}", (ex, HY - 0.41, ez), (0.15, 0.08, 0.15), 흰, lump=0.0)
        part("sphere", f"노란눈{sx}", (ex, HY - 0.475, ez), (0.105, 0.03, 0.105), 노랑, lump=0.0)
        part("sphere", f"눈동자{sx}", (ex, HY - 0.495, ez), (0.05, 0.02, 0.05), M["검은눈"], lump=0.0)
        part("sphere", f"눈빛{sx}", (ex + 0.025, HY - 0.51, ez + 0.035), (0.016, 0.01, 0.018), M["흰빛"], lump=0.0)
        # 흰 눈썹 털 (위로 치켜 올라감)
        part("sphere", f"눈썹{sx}", (0.20 * sx, HY - 0.37, HZ + 0.31), (0.12, 0.05, 0.04), 흰,
             rot=(0, -18 * sx, 0), lump=0.0)
        # 둥근 귀 + 흰 속
        part("sphere", f"귀{sx}", (0.40 * sx, HY + 0.02, HZ + 0.40), (0.14, 0.07, 0.14), 머리, lump=0.0)
        part("sphere", f"귀속{sx}", (0.40 * sx, HY - 0.04, HZ + 0.39), (0.085, 0.03, 0.085), 흰, lump=0.0)
        # 볼의 검은 줄 2개씩
        for j, dz in enumerate((0.02, -0.10)):
            part("sphere", f"볼줄{sx}{j}", (0.50 * sx, HY - 0.15, HZ + dz), (0.11, 0.05, 0.022), 줄,
                 rot=(0, 10 * sx, 15 * sx), lump=0.0)
    # 이마의 검은 줄 (王 자처럼 세 줄)
    for j, dz in enumerate((0.40, 0.33, 0.26)):
        w = (0.10, 0.07, 0.10)[j]
        part("sphere", f"이마줄{j}", (0, HY - 0.36 + 0.04 * j, HZ + dz), (w, 0.04, 0.02), 줄, lump=0.0)


